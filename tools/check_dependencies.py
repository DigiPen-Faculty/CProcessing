"""Report which pinned dependencies have a newer upstream version.

    python tools/check_dependencies.py [--markdown <file>]

Reads the pins this repository keeps (see DEPENDENCIES.md), asks the upstream
projects what is newest, and prints a table. It only reports: updating is a
decision, made by hand with the steps in DEPENDENCIES.md. The GitHub Actions
versions are not checked here; Dependabot does that.

Needs network access. Set GITHUB_TOKEN (or GH_TOKEN) to avoid GitHub's low
anonymous rate limit; the scheduled workflow does. When GITHUB_OUTPUT is set
(GitHub Actions), writes updates=<number of dependencies with updates> to it.
Exits with status 0 whatever it finds; a dependency it could not check is
shown as such.
"""
import json
import os
import re
import sys
import urllib.error
import urllib.request
from pathlib import Path

root = Path(__file__).resolve().parent.parent
API = "https://api.github.com"


def read(path):
    return (root / path).read_text(encoding="utf-8", errors="replace")


def fetch(url, accept="application/json"):
    headers = {"Accept": accept, "User-Agent": "cprocessing-dependency-check"}
    token = os.environ.get("GITHUB_TOKEN") or os.environ.get("GH_TOKEN")
    if token and url.startswith(API):
        headers["Authorization"] = f"Bearer {token}"
    with urllib.request.urlopen(urllib.request.Request(url, headers=headers), timeout=30) as response:
        return response.read().decode("utf-8", errors="replace")


def api(path):
    return json.loads(fetch(API + path, "application/vnd.github+json"))


def version_key(text):
    return tuple(int(part) for part in re.findall(r"\d+", text))


def latest_tag(repo, pattern):
    """The highest tag of a repository that matches the pattern."""
    best = None
    for page in (1, 2, 3):
        tags = api(f"/repos/{repo}/tags?per_page=100&page={page}")
        for tag in tags:
            if re.fullmatch(pattern, tag["name"]) and (best is None or version_key(tag["name"]) > version_key(best)):
                best = tag["name"]
        if len(tags) < 100:
            break
    if best is None:
        raise RuntimeError("no tag matches " + pattern)
    return best


def commits_behind(repo, pin):
    """(commits since the pin, date of the newest commit, names of the files changed)."""
    default = api(f"/repos/{repo}")["default_branch"]
    compare = api(f"/repos/{repo}/compare/{pin}...{default}")
    newest = api(f"/repos/{repo}/commits/{default}")["commit"]["committer"]["date"][:10]
    return compare["ahead_by"], newest, [f["filename"] for f in compare.get("files", [])]


def file_version(text, pattern):
    match = re.search(pattern, text)
    return match.group(1) if match else "?"


# Each check returns (pinned, upstream, status, counts as an update).
# status "current", or what is newer.

def check_tag(pinned, repo, pattern):
    newest = latest_tag(repo, pattern)
    if version_key(newest) > version_key(pinned):
        return pinned, newest, f"newer: {newest}", True
    return pinned, newest, "current", False


def check_commit(pinned, repo, note=None):
    ahead, newest, files = commits_behind(repo, pinned)
    short = pinned[:7]
    if ahead == 0:
        return short, "same commit", "current", False
    status = f"{ahead} commits behind (newest {newest})"
    if note:
        status += "; " + note(files)
    return short, newest, status, True


def stb_note(files):
    changed = [f for f in files if f in ("stb_image.h", "stb_truetype.h", "stb_image_write.h")]
    if not changed:
        return "stb_image.h, stb_truetype.h and stb_image_write.h unchanged"
    return "changed: " + ", ".join(changed)


def dependencies():
    cmake = read("cmake/cprocessing_dependencies.cmake")
    diff_script = read("tools/nanovg_diff.sh")
    tests = read(".github/workflows/tests.yml")

    def pin(text, pattern, what):
        match = re.search(pattern, text, re.M)
        if not match:
            raise RuntimeError(f"cannot find the {what} pin")
        return match.group(1)

    glfw = pin(cmake, r'^set\(CPROCESSING_GLFW_VERSION "([^"]+)"', "GLFW")
    soloud = pin(cmake, r'^set\(CPROCESSING_SOLOUD_COMMIT "([0-9a-f]{40})"', "SoLoud")
    miniaudio = pin(cmake, r'^set\(CPROCESSING_MINIAUDIO_VERSION "([^"]+)"', "miniaudio")
    nanovg = pin(diff_script, r"^NANOVG_COMMIT=([0-9a-f]{40})", "NanoVG")
    stb = pin(diff_script, r"^STB_COMMIT=([0-9a-f]{40})", "stb")
    unity = pin(read("tests/unity/Version.txt"), r"^([0-9a-f]{40})\s*$", "Unity")
    clang_format = pin(tests, r'^\s*CLANG_FORMAT_VERSION: "([^"]+)"', "clang-format")
    mesa = pin(tests, r"^\s*MESA_VERSION: *([0-9.]+)", "Mesa")
    glad = pin(read("CProcessing/third_party/glad/glad.h"), r"generated by glad (\d+\.\d+\.\d+)", "GLAD")

    def clang_format_check():
        newest = json.loads(fetch("https://pypi.org/pypi/clang-format/json"))["info"]["version"]
        if version_key(newest) > version_key(clang_format):
            return clang_format, newest, f"newer: {newest} (its output changes between versions; update the pin and reformat)", True
        return clang_format, newest, "current", False

    def stb_versions():
        image = file_version(read("CProcessing/third_party/nanovg/src/stb_image.h"), r"stb_image - v(\d+\.\d+)")
        truetype = file_version(read("CProcessing/third_party/nanovg/src/stb_truetype.h"), r"stb_truetype\.h - v(\d+\.\d+)")
        write = file_version(read("CProcessing/third_party/stb/stb_image_write.h"), r"stb_image_write - v(\d+\.\d+)")
        return f"stb_image {image}, stb_truetype {truetype}, stb_image_write {write}"

    def glad_check():
        newest = latest_tag("Dav1dde/glad", r"v0\.1\.\d+").lstrip("v")
        # The 0.1 generator is frozen and the header only changes if we regenerate it
        # for a different OpenGL version, so this is information, not an update.
        return glad, newest, "info: regenerate only to change the OpenGL version", False

    return [
        ("GLFW", "https://github.com/glfw/glfw", lambda: check_tag(glfw, "glfw/glfw", r"\d+\.\d+(\.\d+)?")),
        ("SoLoud", "https://github.com/jarikomppa/soloud", lambda: check_commit(soloud, "jarikomppa/soloud")),
        ("miniaudio", "https://github.com/mackron/miniaudio", lambda: check_tag(miniaudio, "mackron/miniaudio", r"\d+\.\d+\.\d+")),
        ("NanoVG", "https://github.com/memononen/nanovg", lambda: check_commit(nanovg, "memononen/nanovg")),
        ("stb (" + stb_versions() + ")", "https://github.com/nothings/stb", lambda: check_commit(stb, "nothings/stb", stb_note)),
        ("Unity", "https://github.com/ThrowTheSwitch/Unity", lambda: check_commit(unity, "ThrowTheSwitch/Unity")),
        ("GLAD (0.1 generator)", "https://github.com/Dav1dde/glad", glad_check),
        ("clang-format", "https://pypi.org/project/clang-format/", clang_format_check),
        ("Mesa (CI software GL on Windows)", "https://github.com/pal1000/mesa-dist-win", lambda: check_tag(mesa, "pal1000/mesa-dist-win", r"\d+\.\d+\.\d+")),
    ]


def main():
    rows = []
    updates = 0
    for name, url, check in dependencies():
        try:
            pinned, upstream, status, is_update = check()
        except (urllib.error.URLError, RuntimeError, KeyError, ValueError, OSError) as error:
            pinned, upstream, status, is_update = "?", "?", f"could not check ({error})", False
        updates += 1 if is_update else 0
        flag = "**update**" if is_update else ""
        rows.append(f"| [{name}]({url}) | {pinned} | {upstream} | {status} {flag}".rstrip() + " |")

    lines = [
        "Pinned dependencies against upstream (`tools/check_dependencies.py`). This only reports; "
        "update by hand with the steps in DEPENDENCIES.md.",
        "",
        "| Dependency | Pinned | Newest upstream | Status |",
        "|---|---|---|---|",
        *rows,
        "",
        f"{updates} dependenc{'y has an update' if updates == 1 else 'ies have updates'}. "
        "GitHub Actions versions are checked by Dependabot.",
    ]
    report = "\n".join(lines) + "\n"
    print(report)
    if "--markdown" in sys.argv:
        Path(sys.argv[sys.argv.index("--markdown") + 1]).write_text(report, encoding="utf-8")
    if os.environ.get("GITHUB_OUTPUT"):
        with open(os.environ["GITHUB_OUTPUT"], "a", encoding="utf-8") as out:
            out.write(f"updates={updates}\n")
    return 0


sys.exit(main())
